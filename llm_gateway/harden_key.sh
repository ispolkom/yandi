#!/usr/bin/env bash
# llm_gateway/harden_key.sh — одноразовое усиление ключа узла до
# состояния "никто, включая root, не может его переписать без
# намеренного, отдельного шага снятия защиты".
#
# ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ СКРИПТ, А НЕ ЧАСТЬ КОДА PYTHON:
# создание ключа (случайные байты, права 0600) код делает сам,
# автоматически, без root — см. llm_gateway/secure_store.py. А вот
# СНЯТИЕ права на запись даже у root — это системная операция
# (chattr), которая физически требует root прямо сейчас, один раз.
# Ни ИИ-ассистент, ни сам код Python не может выполнить sudo без
# участия человека — это одноразовое действие ты выполняешь сам.
#
# Что делает:
#   1. Проверяет, что ключ уже существует (создаётся кодом при первом
#      реальном использовании — см. secure_store.py) — не создаёт его
#      здесь, только усиливает уже существующий файл.
#   2. Ставит на файл атрибут "immutable" (chattr +i) — после этого
#      ни один процесс, ВКЛЮЧАЯ root, не может изменить или удалить
#      файл, пока кто-то намеренно не снимет этот атрибут (chattr -i,
#      тоже требует root) — это и есть "root аннулируется": в моменте
#      после этого скрипта никто не имеет действующего пути переписать
#      ключ, пока кто-то снова не станет root И не снимет chattr явно.
#   3. Права файла остаются 0400 (только чтение, только владельцем) —
#      это уже сделал secure_store.py при создании, тут не трогаем.
#
# ВАЖНО про удаление: chattr +i защищает и от изменения, И от
# удаления — то есть после этого скрипта даже "стереть всё и начать
# заново" требует sudo (снять chattr, потом удалить). Это осознанный
# выбор: ключ узла — это не обычные данные, случайное "rm" не должно
# необратимо решать судьбу криптографической идентичности ноды. Сами
# ДАННЫЕ (настройки моделей в node_config.sqlite) этим скриптом никак
# не защищаются — их пользователь может стереть в любой момент без
# root, как обычно.
#
# Использование:
#   sudo ./llm_gateway/harden_key.sh [путь_к_ключу]
# Без аргумента берёт путь по умолчанию (~/.local/share/yandi/keys/node_kek.bin)
# либо из переменной YANDI_KEK_PATH, если она задана.

set -euo pipefail

if [[ "${EUID}" -ne 0 ]]; then
  echo "Нужен root (запусти через sudo) — это единственный шаг, которому он вообще требуется." >&2
  exit 1
fi

KEY_PATH="${1:-${YANDI_KEK_PATH:-$HOME/.local/share/yandi/keys/node_kek.bin}}"

if [[ ! -f "$KEY_PATH" ]]; then
  echo "Файл ключа не найден: $KEY_PATH" >&2
  echo "Сначала запусти ноду один раз (или python3 -m llm_gateway.setup) — ключ создаётся кодом автоматически при первом использовании." >&2
  exit 1
fi

if ! command -v chattr >/dev/null 2>&1; then
  echo "chattr не найден — эта защита работает только на файловых системах с поддержкой extended attributes (ext2/3/4, xfs, btrfs)." >&2
  exit 1
fi

CURRENT_ATTRS="$(lsattr "$KEY_PATH" 2>/dev/null | awk '{print $1}')"
if [[ "$CURRENT_ATTRS" == *i* ]]; then
  echo "Уже защищён (immutable): $KEY_PATH"
  exit 0
fi

chmod 400 "$KEY_PATH"
chattr +i "$KEY_PATH"

echo "Готово: $KEY_PATH теперь неизменяем — не может быть переписан или удалён никем, включая root,"
echo "пока кто-то явно не выполнит: sudo chattr -i \"$KEY_PATH\""
echo "Обычный root-доступ для повседневной работы ноды больше не нужен и не используется."
