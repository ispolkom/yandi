# ------------------------------------------------------------
# P2.2 (YANDI_FULL_PIPELINE_AUDIT.md, §23/§33) — САМЫЙ
# СПЕКУЛЯТИВНЫЙ пункт из P0-P3 плана этого аудита.
#
# Ранее только orch_synthesizer.py имел concurrency gate
# (Semaphore(2)) для своих вызовов Ollama. orch_web_query.py
# (используется для main/refutation query formulation И для
# до 8 claim-specific query generation вызовов в PASS2) не имел
# никакого gate вообще — до 3 потоков могли одновременно слать
# generation запросы на тот же локальный Ollama без координации.
#
# Этот semaphore НЕ подтверждён рантайм-профилированием — аудит
# явно отметил, что реальный эффект (помогает или вредит) зависит
# от того, как Ollama сам сериализует generation на GPU/CPU, что
# статически установить нельзя. Использован тот же размер (2),
# что уже проверен в orch_synthesizer.py, для минимального
# сюрприза в поведении — но это НЕ научно откалиброванное число.
GENERATION_SEMAPHORE = threading.Semaphore(2)

# Единая модель для всех ролей: дирижёр, аналитик, датасет
MODEL         = "heretic:q8"

